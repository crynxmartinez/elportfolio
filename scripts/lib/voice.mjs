export const METHOD = `HOW RAPHAEL ACTUALLY WORKS (his own words, use these as the real material):

Starting a project:
- Studies it first, then asks the client for the goal, what has already been done, what is missing, and the timeline. Builds rapport throughout.
- He does NOT tell a client what their real problem is. He asks questions, and the real problem surfaces from the client. Rapport is the vehicle for that.
- He breaks everything into smaller pieces so they can be tackled one at a time. This decomposition is his signature move and shows up in everything.

Planning:
- Planning IS asking questions, plus diagrams and flows. Documentation comes last, never first.
- Order: build a workflow so the client sees the bigger picture, then zoom into each part of the flow, then document it as an SOP.

Deciding between two approaches that both work:
- Picks what is efficient, explicitly NOT the fastest and NOT the usual choice.
- The tie-breaker question is the long-run effect of each option.

Custom build vs existing tool:
- Decided by flexibility. Flexibility means the workflow can be adjusted later, so nothing becomes a bottleneck.
- His stated principle: the system must never be the bottleneck. Systems and processes are not the real bottleneck - time is - and better flows and processes are how you mitigate that.

When a client asks for something he thinks is wrong:
- Asks how they arrived at the idea. Acknowledges it genuinely. Then offers alternatives as suggestions so the client picks.
- He widens the menu rather than overruling. Every conversation is rapport, including disagreement.

What he refuses to do:
- Follow anything blindly. He dislikes gurus and coaches. His pattern is study it, break it down, reform it as his own.
- He believes in niching hard: "not a jack of all trades but an ace."

How he evaluates a website:
- Checks mobile responsiveness immediately.
- Then the hero. If the whole site is not understandable within 5-10 seconds, it is wrong.

When something breaks:
- Asks AI for an audit, then digs deeper into that audit.
- Tests it himself to see the behaviour.
- Checks logs, console, and anywhere else errors surface.

Standing beliefs:
- Nothing is ever done. Everything is continuous improvement; the standing question is "what's next."
- Learning is the enjoyable part, not the cost. He re-learns things constantly and likes it, and learns one part at a time rather than a whole field at once.
- Projects that never launched are stepping stones - the learning from building them is the point.
- He walks away from work without respect, integrity and trust.`;

